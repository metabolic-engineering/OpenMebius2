classdef GridSearchConfidenceIntervalSolver

    methods

        function result = solve( ...
                ~, ...
                problem, ...
                bestFlux, ...
                baseRightHandSide, ...
                settings, ...
                evaluationFunction, ...
                reversibleReactionIndices, ...
                options ...
            )

            arguments
                ~
                problem (1, 1) openmebius.mfa.MFAProblem
                bestFlux (:, 1) double
                baseRightHandSide (:, 1) double
                settings (1, 1) openmebius.mfa ...
                    .GridSearchConfidenceIntervalSettings
                evaluationFunction (1, 1) function_handle
                reversibleReactionIndices (:, 2) double = zeros(0, 2)
                options.ProfileFluxIndices (:, 1) double = zeros(0, 1)
                options.ObjectiveThreshold (1, 1) double ...
                    {mustBeFinite, mustBeNonnegative}
                options.BestObjective (1, 1) double ...
                    {mustBeFinite, mustBeNonnegative}
                options.InitialIndependentValues double = []
                options.MessageReporter (1, 1) function_handle = ...
                    @(~, ~) []
                options.CancellationRequested ...
                    (1, 1) function_handle = @() false
            end

            startedAt = tic;
            report = options.MessageReporter;

            if options.BestObjective > options.ObjectiveThreshold
                error( ...
                    "OpenMebius2:GridSearchConfidenceIntervalSolver:" + ...
                    "BestObjectiveExceedsThreshold", ...
                    "The best objective must not exceed the objective " + ...
                "threshold.");
            end

            [forwardBest, forwardLower, forwardUpper] = ...
                openmebius.mfa.GridSearchConfidenceIntervalSolver ...
                .forwardFluxData( ...
                problem, bestFlux, reversibleReactionIndices);

            profileIndices = options.ProfileFluxIndices;

            if isempty(profileIndices)
                profileIndices = (1:numel(forwardBest)).';
            end

            openmebius.mfa.GridSearchConfidenceIntervalSolver ...
                .validateProfileIndices( ...
                profileIndices, numel(forwardBest));

            initialValues = options.InitialIndependentValues;

            if isempty(initialValues)
                initialValues = ...
                    problem.extractIndependentValues(baseRightHandSide);
            end

            profileCount = numel(profileIndices);
            fixedCells = cell(profileCount, 1);
            objectiveCells = cell(profileCount, 1);
            useFvaBounds = false(profileCount, 1);
            canceled = false;

            report( ...
                "info", ...
                "Calculating grid-search profiles for " + ...
                string(profileCount) + " fluxes.");

            if settings.ExecutionMode.isParallel()

                parfor profileNumber = 1:profileCount
                    fluxIndex = profileIndices(profileNumber);

                    [fixedCells{profileNumber}, ...
                         objectiveCells{profileNumber}, ...
                         useFvaBounds(profileNumber)] = ...
                        openmebius.mfa ...
                        .GridSearchConfidenceIntervalSolver ...
                        .evaluateProfile( ...
                        problem, ...
                        baseRightHandSide, ...
                        settings, ...
                        evaluationFunction, ...
                        reversibleReactionIndices, ...
                        fluxIndex, ...
                        forwardBest(fluxIndex), ...
                        forwardLower(fluxIndex), ...
                        forwardUpper(fluxIndex), ...
                        options.BestObjective, ...
                        options.ObjectiveThreshold, ...
                        initialValues, ...
                        @() false);
                end

                canceled = logical(options.CancellationRequested());

            else

                for profileNumber = 1:profileCount

                    if logical(options.CancellationRequested())
                        canceled = true;
                        break
                    end

                    fluxIndex = profileIndices(profileNumber);

                    report( ...
                        "info", ...
                        "Grid-search profile: " + ...
                        string(profileNumber) + "/" + ...
                        string(profileCount));

                    [fixedCells{profileNumber}, ...
                         objectiveCells{profileNumber}, ...
                         useFvaBounds(profileNumber)] = ...
                        openmebius.mfa ...
                        .GridSearchConfidenceIntervalSolver ...
                        .evaluateProfile( ...
                        problem, ...
                        baseRightHandSide, ...
                        settings, ...
                        evaluationFunction, ...
                        reversibleReactionIndices, ...
                        fluxIndex, ...
                        forwardBest(fluxIndex), ...
                        forwardLower(fluxIndex), ...
                        forwardUpper(fluxIndex), ...
                        options.BestObjective, ...
                        options.ObjectiveThreshold, ...
                        initialValues, ...
                        options.CancellationRequested);

                    if logical(options.CancellationRequested())
                        canceled = true;
                        break
                    end

                end

            end

            completed = ~cellfun(@isempty, fixedCells);
            profileIndices = profileIndices(completed);
            fixedCells = fixedCells(completed);
            objectiveCells = objectiveCells(completed);
            useFvaBounds = useFvaBounds(completed);

            [fixedFluxValues, objectiveValues] = ...
                openmebius.mfa.GridSearchConfidenceIntervalSolver ...
                .packProfiles(fixedCells, objectiveCells);
            minimumObjectives = min( ...
                objectiveValues, [], 3, "omitnan");

            lowerBounds = nan(numel(profileIndices), 1);
            upperBounds = nan(numel(profileIndices), 1);

            for profileNumber = 1:numel(profileIndices)
                fluxIndex = profileIndices(profileNumber);
                targets = fixedFluxValues(profileNumber, :, 1);

                if useFvaBounds(profileNumber)
                    lowerBounds(profileNumber) = ...
                        forwardLower(fluxIndex);
                    upperBounds(profileNumber) = ...
                        forwardUpper(fluxIndex);
                    continue
                end

                validTargets = isfinite(targets);
                targets = targets(validTargets);
                objectives = minimumObjectives( ...
                    profileNumber, validTargets).';

                [lowerBounds(profileNumber), ...
                     upperBounds(profileNumber)] = ...
                    openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .estimateBounds( ...
                    targets(:), ...
                    objectives, ...
                    forwardBest(fluxIndex), ...
                    options.ObjectiveThreshold);
            end

            profileData = openmebius.mfa.GridSearchProfileData( ...
                FluxIndices = profileIndices, ...
                FixedFluxValues = fixedFluxValues, ...
                MinimumSumOfSquares = objectiveValues);

            result = openmebius.mfa ...
                .GridSearchConfidenceIntervalResult( ...
                LowerBounds = lowerBounds, ...
                UpperBounds = upperBounds, ...
                ProfileData = profileData, ...
                ElapsedTime = toc(startedAt), ...
                IsCanceled = canceled);

        end % method solve

    end % methods

    methods (Static, Access = private)

        function [fixedValues, objectives, useFvaBounds] = ...
                evaluateProfile( ...
                problem, ...
                baseRightHandSide, ...
                settings, ...
                evaluationFunction, ...
                reversiblePairs, ...
                fluxIndex, ...
                bestValue, ...
                lowerBound, ...
                upperBound, ...
                bestObjective, ...
                objectiveThreshold, ...
                initialCandidates, ...
                cancellationRequested ...
            )

            useFvaBounds = ...
                upperBound - lowerBound < settings.MinimumFluxRange;

            if useFvaBounds
                targets = unique( ...
                    [lowerBound, bestValue, upperBound], "sorted");
                fixedValues = repmat( ...
                    reshape(targets, 1, [], 1), ...
                    1, 1, settings.IterationCount);
                objectives = nan(size(fixedValues));
                return
            end

            fluxWeights = openmebius.mfa ...
                .GridSearchConfidenceIntervalSolver.profileWeights( ...
                size(problem.Stoichiometry, 2), ...
                fluxIndex, ...
                reversiblePairs);

            if settings.IntervalMode.isAutomatic()
                lowerProfileBound = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .findAutomaticProfileBound( ...
                    problem, ...
                    baseRightHandSide, ...
                    evaluationFunction, ...
                    fluxWeights, ...
                    bestValue, ...
                    lowerBound, ...
                    bestObjective, ...
                    objectiveThreshold, ...
                    settings, ...
                    initialCandidates, ...
                    cancellationRequested);
                upperProfileBound = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .findAutomaticProfileBound( ...
                    problem, ...
                    baseRightHandSide, ...
                    evaluationFunction, ...
                    fluxWeights, ...
                    bestValue, ...
                    upperBound, ...
                    bestObjective, ...
                    objectiveThreshold, ...
                    settings, ...
                    initialCandidates, ...
                    cancellationRequested);
                targets = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .buildAutomaticTargets( ...
                    bestValue, ...
                    lowerProfileBound, ...
                    upperProfileBound, ...
                    settings.PointCount);
            else
                targets = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .buildFixedDeltaTargets( ...
                    bestValue, lowerBound, upperBound, settings);
            end

            [fixedValues, objectives] = openmebius.mfa ...
                .GridSearchConfidenceIntervalSolver.evaluateTargets( ...
                problem, ...
                baseRightHandSide, ...
                evaluationFunction, ...
                fluxWeights, ...
                targets, ...
                settings.IterationCount, ...
                initialCandidates, ...
                cancellationRequested);

            [fixedValues, objectives] = openmebius.mfa ...
                .GridSearchConfidenceIntervalSolver ...
                .extendProfileToBoundary( ...
                problem, ...
                baseRightHandSide, ...
                evaluationFunction, ...
                fluxWeights, ...
                fixedValues, ...
                objectives, ...
                bestValue, ...
                lowerBound, ...
                upperBound, ...
                objectiveThreshold, ...
                settings.IterationCount, ...
                initialCandidates, ...
                cancellationRequested);

        end % method evaluateProfile

        function profileBound = findAutomaticProfileBound( ...
                problem, ...
                baseRightHandSide, ...
                evaluationFunction, ...
                fluxWeights, ...
                bestValue, ...
                fvaBound, ...
                bestObjective, ...
                objectiveThreshold, ...
                settings, ...
                initialCandidates, ...
                cancellationRequested ...
            )

            if fvaBound == bestValue
                profileBound = bestValue;
                return
            end

            objectiveMargin = ...
                (objectiveThreshold - bestObjective) / 2;
            % Accept RSS values strictly between the threshold and half
            % of the best-to-threshold gap above it.
            acceptableLower = objectiveThreshold;
            acceptableUpper = objectiveThreshold + objectiveMargin;
            bestSide = bestValue;
            fvaSide = fvaBound;
            profileBound = bestValue;
            closestDistance = inf;

            for trial = 1:settings.MaximumTrial

                if logical(cancellationRequested())
                    return
                end

                candidateFlux = (bestSide + fvaSide) / 2;
                trialObjectives = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver.evaluateTarget( ...
                    problem, ...
                    baseRightHandSide, ...
                    evaluationFunction, ...
                    fluxWeights, ...
                    candidateFlux, ...
                    settings.IterationCount, ...
                    initialCandidates);
                candidateObjective = min( ...
                    trialObjectives, [], "omitnan");

                if isfinite(candidateObjective)
                    distance = abs( ...
                        candidateObjective - objectiveThreshold);

                    if distance < closestDistance
                        closestDistance = distance;
                        profileBound = candidateFlux;
                    end

                    if candidateObjective > acceptableLower && ...
                            candidateObjective < acceptableUpper
                        profileBound = candidateFlux;
                        return
                    end

                elseif ~isfinite(closestDistance)
                    profileBound = candidateFlux;
                end

                if ~isfinite(candidateObjective) || ...
                        candidateObjective >= acceptableUpper
                    % Candidate is beyond the threshold-side band.
                    fvaSide = candidateFlux;
                else
                    % Candidate is still on the best-fit side.
                    bestSide = candidateFlux;
                end

                if bestSide == fvaSide
                    return
                end

            end

        end % findAutomaticProfileBound

        function targets = buildAutomaticTargets( ...
                bestValue, lowerBound, upperBound, pointCount)

            sideCount = pointCount / 2;
            lowerTargets = linspace( ...
                lowerBound, bestValue, sideCount + 1);
            upperTargets = linspace( ...
                bestValue, upperBound, sideCount + 1);
            targets = [lowerTargets, upperTargets(2:end)];
            targets = sort(targets);

        end % buildAutomaticTargets

        function targets = buildFixedDeltaTargets( ...
                bestValue, lowerBound, upperBound, settings)

            count = settings.PointCount;
            lowerCount = floor((count - 1) / 2);
            upperCount = count - lowerCount - 1;
            offsets = -lowerCount:upperCount;
            targets = bestValue + offsets * settings.Delta;
            targets = min(max(targets, lowerBound), upperBound);
            targets = sort(targets);

        end % buildFixedDeltaTargets

        function [fixedValues, objectives] = evaluateTargets( ...
                problem, ...
                baseRightHandSide, ...
                evaluationFunction, ...
                fluxWeights, ...
                targets, ...
                trialCount, ...
                initialCandidates, ...
                cancellationRequested ...
            )

            pointCount = numel(targets);
            fixedValues = repmat( ...
                reshape(targets, 1, pointCount, 1), ...
                1, 1, trialCount);
            objectives = nan(1, pointCount, trialCount);

            for point = 1:pointCount

                if logical(cancellationRequested())
                    return
                end

                pointObjectives = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver.evaluateTarget( ...
                    problem, ...
                    baseRightHandSide, ...
                    evaluationFunction, ...
                    fluxWeights, ...
                    targets(point), ...
                    trialCount, ...
                    initialCandidates);
                objectives(1, point, :) = reshape( ...
                    pointObjectives, 1, 1, trialCount);
            end

        end % evaluateTargets

        function [fixedValues, objectives] = extendProfileToBoundary( ...
                problem, ...
                baseRightHandSide, ...
                evaluationFunction, ...
                fluxWeights, ...
                fixedValues, ...
                objectives, ...
                bestValue, ...
                lowerBound, ...
                upperBound, ...
                objectiveThreshold, ...
                trialCount, ...
                initialCandidates, ...
                cancellationRequested ...
            )

            targets = reshape(fixedValues(1, :, 1), 1, []);
            minimumObjectives = reshape( ...
                min(objectives, [], 3, "omitnan"), 1, []);
            lowerMask = targets < bestValue;
            upperMask = targets > bestValue;
            lowerTargets = zeros(1, 0);
            lowerObjectives = nan(1, 0, trialCount);
            upperTargets = zeros(1, 0);
            upperObjectives = nan(1, 0, trialCount);

            if any(lowerMask) && ...
                    ~openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .hasThresholdBoundary( ...
                    minimumObjectives(lowerMask), objectiveThreshold)
                lowerEdge = min(targets(lowerMask));
                lowerStep = (bestValue - lowerEdge) / ...
                    nnz(lowerMask);
                [lowerTargets, lowerObjectives] = ...
                    openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .evaluateProfileExtension( ...
                    problem, ...
                    baseRightHandSide, ...
                    evaluationFunction, ...
                    fluxWeights, ...
                    lowerEdge, ...
                    lowerBound, ...
                    -1, ...
                    lowerStep, ...
                    objectiveThreshold, ...
                    trialCount, ...
                    initialCandidates, ...
                    cancellationRequested);
            end

            if any(upperMask) && ...
                    ~openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .hasThresholdBoundary( ...
                    minimumObjectives(upperMask), objectiveThreshold)
                upperEdge = max(targets(upperMask));
                upperStep = (upperEdge - bestValue) / ...
                    nnz(upperMask);
                [upperTargets, upperObjectives] = ...
                    openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver ...
                    .evaluateProfileExtension( ...
                    problem, ...
                    baseRightHandSide, ...
                    evaluationFunction, ...
                    fluxWeights, ...
                    upperEdge, ...
                    upperBound, ...
                    1, ...
                    upperStep, ...
                    objectiveThreshold, ...
                    trialCount, ...
                    initialCandidates, ...
                    cancellationRequested);
            end

            targets = [targets, lowerTargets, upperTargets];
            objectives = cat( ...
                2, objectives, lowerObjectives, upperObjectives);
            [targets, order] = sort(targets);
            objectives = objectives(:, order, :);
            fixedValues = repmat( ...
                reshape(targets, 1, [], 1), 1, 1, trialCount);

        end % extendProfileToBoundary

        function [targets, objectives] = evaluateProfileExtension( ...
                problem, ...
                baseRightHandSide, ...
                evaluationFunction, ...
                fluxWeights, ...
                startValue, ...
                fvaBound, ...
                direction, ...
                step, ...
                objectiveThreshold, ...
                trialCount, ...
                initialCandidates, ...
                cancellationRequested ...
            )

            targets = zeros(1, 0);
            objectives = nan(1, 0, trialCount);
            currentValue = startValue;

            if ~isfinite(step) || step <= 0
                return
            end

            while direction * (fvaBound - currentValue) > 0

                if logical(cancellationRequested())
                    return
                end

                candidate = currentValue + direction * step;

                if direction < 0
                    candidate = max(candidate, fvaBound);
                else
                    candidate = min(candidate, fvaBound);
                end

                if candidate == currentValue
                    return
                end

                pointObjectives = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver.evaluateTarget( ...
                    problem, ...
                    baseRightHandSide, ...
                    evaluationFunction, ...
                    fluxWeights, ...
                    candidate, ...
                    trialCount, ...
                    initialCandidates);
                targets(end + 1) = candidate; %#ok<AGROW>
                objectives = cat( ...
                    2, objectives, ...
                    reshape(pointObjectives, 1, 1, trialCount));
                currentValue = candidate;
                minimumObjective = min( ...
                    pointObjectives, [], "omitnan");

                if ~isfinite(minimumObjective) || ...
                        minimumObjective > objectiveThreshold
                    return
                end

            end

        end % evaluateProfileExtension

        function tf = hasThresholdBoundary(objectives, threshold)

            tf = any(~isfinite(objectives) | objectives > threshold);

        end % hasThresholdBoundary

        function [fixedValues, objectiveValues] = ...
                packProfiles(fixedCells, objectiveCells)

            profileCount = numel(fixedCells);

            if profileCount == 0
                fixedValues = zeros(0, 0, 0);
                objectiveValues = zeros(0, 0, 0);
                return
            end

            pointCounts = cellfun(@(value) size(value, 2), fixedCells);
            trialCounts = cellfun(@(value) size(value, 3), fixedCells);
            pointCount = max(pointCounts);
            trialCount = max(trialCounts);
            fixedValues = nan(profileCount, pointCount, trialCount);
            objectiveValues = nan(profileCount, pointCount, trialCount);

            for profileNumber = 1:profileCount
                points = pointCounts(profileNumber);
                trials = trialCounts(profileNumber);
                fixedValues(profileNumber, 1:points, 1:trials) = ...
                    fixedCells{profileNumber};
                objectiveValues(profileNumber, 1:points, 1:trials) = ...
                    objectiveCells{profileNumber};
            end

        end % packProfiles

        function objectives = evaluateTarget( ...
                problem, ...
                baseRightHandSide, ...
                evaluationFunction, ...
                fluxWeights, ...
                target, ...
                trialCount, ...
                initialCandidates ...
            )

            objectives = nan(1, trialCount);
            candidateCount = size(initialCandidates, 2);
            [equalityMatrix, equalityRightHandSide] = ...
                problem.fixedFluxEqualities( ...
                fluxWeights, ...
                target, ...
                BaseRightHandSide = baseRightHandSide);

            for trial = 1:trialCount
                candidate = initialCandidates( ...
                    :, mod(trial - 1, candidateCount) + 1);
                iterationResult = evaluationFunction( ...
                    equalityMatrix, ...
                    equalityRightHandSide, ...
                    candidate);

                if ~isa(iterationResult, ...
                    "openmebius.mfa.MFAIterationResult") || ...
                        iterationResult.IsError || ...
                        ~isfinite(iterationResult.ObjectiveValue)
                    continue
                end

                objectives(trial) = iterationResult.ObjectiveValue;
            end

        end % evaluateTarget

        function weights = profileWeights( ...
                fullFluxCount, outputIndex, reversiblePairs)

            reverseIndices = reversiblePairs(:, 2);
            retainedIndices = setdiff( ...
                (1:fullFluxCount).', reverseIndices, "stable");
            expandedIndex = retainedIndices(outputIndex);
            weights = zeros(fullFluxCount, 1);
            weights(expandedIndex) = 1;

            pair = find( ...
                reversiblePairs(:, 1) == expandedIndex, 1);

            if ~isempty(pair)
                weights(reversiblePairs(pair, 2)) = -1;
            end

        end % method profileWeights

        function [lowerBound, upperBound] = estimateBounds( ...
                targets, objectives, bestValue, threshold)

            [targets, order] = sort(targets);
            objectives = objectives(order);
            accepted = isfinite(objectives) & ...
                objectives <= threshold;
            [~, center] = min(abs(targets - bestValue));

            if ~accepted(center)
                lowerBound = NaN;
                upperBound = NaN;
                return
            end

            first = center;
            last = center;

            while first > 1 && accepted(first - 1)
                first = first - 1;
            end

            while last < numel(targets) && accepted(last + 1)
                last = last + 1;
            end

            lowerBound = targets(first);
            upperBound = targets(last);

            if first > 1 && isfinite(objectives(first - 1))
                lowerBound = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver.interpolateCrossing( ...
                    targets(first - 1), objectives(first - 1), ...
                    targets(first), objectives(first), threshold);
            end

            if last < numel(targets) && ...
                    isfinite(objectives(last + 1))
                upperBound = openmebius.mfa ...
                    .GridSearchConfidenceIntervalSolver.interpolateCrossing( ...
                    targets(last), objectives(last), ...
                    targets(last + 1), objectives(last + 1), ...
                    threshold);
            end

        end % method estimateBounds

        function value = interpolateCrossing( ...
                x1, y1, x2, y2, threshold)

            if y1 == y2
                value = x2;
                return
            end

            value = x1 + ...
                (threshold - y1) * (x2 - x1) / (y2 - y1);
            value = min(max(value, min(x1, x2)), max(x1, x2));

        end % method interpolateCrossing

        function [best, lower, upper] = forwardFluxData( ...
                problem, bestFlux, reversiblePairs)

            best = openmebius.mfa.ReversibleFluxMapper.mapFlux( ...
                bestFlux, reversiblePairs);
            [lower, upper] = ...
                openmebius.mfa.ReversibleFluxMapper.mapBounds( ...
                problem.LowerBounds, ...
                problem.UpperBounds, ...
                reversiblePairs);

        end % method forwardFluxData

        function validateProfileIndices(indices, fluxCount)

            if isempty(indices) || ...
                    any(~isfinite(indices)) || ...
                    any(indices < 1) || ...
                    any(indices > fluxCount) || ...
                    any(indices ~= fix(indices)) || ...
                    numel(unique(indices)) ~= numel(indices)
                error( ...
                    "OpenMebius2:GridSearchCI:" + ...
                    "InvalidProfileFluxIndices", ...
                "Profile flux indices must be unique valid integers.");
            end

        end % method validateProfileIndices

    end % methods (Static, Access = private)

end % classdef
