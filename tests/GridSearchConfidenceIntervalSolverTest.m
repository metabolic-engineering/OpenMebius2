        function result = unexpectedEvaluation()

            error( ...
                "GridSearchConfidenceIntervalSolverTest:" + ...
                "UnexpectedEvaluation", ...
                "Grid search should have been skipped.");

        end

        function result = evaluateExtendedProfilePoint( ...
                ~, equalityRightHandSide, initialValues, scale)

            result = openmebius.mfa.MFAIterationResult( ...
                IndependentValues = initialValues, ...
                Flux = [5; equalityRightHandSide], ...
                MDV = zeros(0, 1), ...
                ObjectiveValue = ...
                scale * (equalityRightHandSide - 5) ^ 2, ...
                ExitFlag = 1);

        end

        function result = evaluateMixedProfilePoint( ...
                ~, equalityRightHandSide, initialValues)

            result = openmebius.mfa.MFAIterationResult( ...
                IndependentValues = initialValues, ...
                Flux = [5; 0.50000025; equalityRightHandSide], ...
                MDV = zeros(0, 1), ...
                ObjectiveValue = ...
                0.1 * (equalityRightHandSide - 5) ^ 2, ...
                ExitFlag = 1);

        end

        function result = evaluateAutomaticProfilePoint( ...
