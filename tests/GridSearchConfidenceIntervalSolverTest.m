        function mixedSkippedAndExtendedProfilesUseNaNPadding(testCase)

            problem = openmebius.mfa.MFAProblem( ...
                Stoichiometry = eye(3), ...
                RightHandSide = [5; 0.50000025; 5], ...
                LowerBounds = [0; 0.5; 0], ...
                UpperBounds = [10; 0.5000005; 10], ...
                IndependentMask = [false; true; true], ...
                BoundaryReactionMask = [false; true; true]);
            settings = openmebius.mfa ...
                .GridSearchConfidenceIntervalSettings( ...
                ExecutionMode = openmebius.mfa ...
                .GridSearchExecutionMode.Serial, ...
                PointCount = 10, ...
                IterationCount = 1, ...
                MaximumTrial = 1, ...
                MinimumFluxRange = 1e-6);
            progress = helpers.AnalysisProgressRecorder();

            result = openmebius.mfa ...
                .GridSearchConfidenceIntervalSolver().solve( ...
                problem, ...
                [5; 0.50000025; 5], ...
                [5; 0.50000025; 5], ...
                settings, ...
                @(equalityMatrix, equalityRightHandSide, ...
                initialValues) ...
                GridSearchConfidenceIntervalSolverTest ...
                .evaluateMixedProfilePoint( ...
                equalityMatrix, equalityRightHandSide, ...
                initialValues), ...
                zeros(0, 2), ...
                ProfileFluxIndices = [2; 3], ...
                ObjectiveThreshold = 1, ...
                BestObjective = 0, ...
                InitialIndependentValues = [0.50000025; 5], ...
                ProgressReporter = @(completed, total) ...
                progress.record(completed, total));

            fixedValues = result.ProfileData.FixedFluxValues;
            testCase.verifySize(fixedValues, [2, 15]);
            testCase.verifyEqual( ...
                fixedValues(1, 1:3), ...
                [0.5, 0.50000025, 0.5000005]);
            testCase.verifyTrue(all(isnan(fixedValues(1, 4:end))));
            testCase.verifyEqual( ...
                result.LowerBounds, [0.5; 1.846153846153846], ...
                AbsTol = 1e-12);
            testCase.verifyEqual( ...
                result.UpperBounds, [0.5000005; 8.153846153846153], ...
                AbsTol = 1e-12);
            testCase.verifyEqual(progress.Completed, [0; 1]);
            testCase.verifyEqual(progress.Total, [1; 1]);

        end

