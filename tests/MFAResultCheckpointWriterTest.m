        function createsBackwardCompatibleMonteCarloCheckpoint(testCase)

            settings = openmebius.mfa.ConfidenceIntervalSettings();
            output = struct(flux = [9; 10], MDV = [0.2; 0.8]);
            writer = ...
                openmebius.infrastructure.result.MFAResultCheckpointWriter();
            checkpoint = ...
                writer.createMonteCarloConfidenceIntervalCheckpoint( ...
                [1, 2; 3, 4], ...
                [5, 6; 7, 8], ...
                settings, ...
                output, ...
                TimestampUnix = 30.5);

            testCase.verifyEqual(checkpoint.DataPath, "/CI");
            testCase.verifyEqual(checkpoint.FinalFluxLB, [2; 4]);
            testCase.verifyEqual(checkpoint.FinalFluxUB, [6; 8]);
            testCase.verifyEqual(checkpoint.Value.time, 30.5);
            testCase.verifyEqual(checkpoint.Value.fluxLB, [1, 2; 3, 4]);
            testCase.verifyEqual(checkpoint.Value.fluxUB, [5, 6; 7, 8]);
