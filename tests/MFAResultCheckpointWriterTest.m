        function createsGridSearchCheckpoint(testCase)

            profile = openmebius.mfa.GridSearchProfileData( ...
                FluxIndices = [1; 3], ...
                FixedFluxValues = cat( ...
                3, [1, 2; 4, 5], [1, 2; 4, 5]), ...
                MinimumSumOfSquares = cat( ...
                3, [7, 4; 9, 6], [6, 5; 8, 7]));
            output = struct( ...
                profile = profile, ...
                time = 12.5, ...
                bestObjective = 3.5, ...
                objectiveThreshold = 6.5);
            settings = openmebius.mfa.ConfidenceIntervalSettings( ...
                Enabled = true, ...
                Method = openmebius.mfa ...
                .ConfidenceIntervalMethod.GridSearch);
            writer = openmebius.infrastructure.result ...
                .MFAResultCheckpointWriter();

            checkpoint = writer ...
                .createGridSearchConfidenceIntervalCheckpoint( ...
                [0.5; 3.5], ...
                [2.5; 5.5], ...
                settings, ...
                output, ...
                ["R1"; "R2"; "R3"; "biomass"], ...
                TimestampUnix = 40.25);

            testCase.verifyEqual( ...
                checkpoint.Value.algorithm, "Grid search");
            testCase.verifyEqual( ...
                checkpoint.FinalFluxLB, [0.5; NaN; 3.5; NaN]);
            testCase.verifyEqual( ...
                checkpoint.FinalFluxUB, [2.5; NaN; 5.5; NaN]);
            testCase.verifyEqual( ...
                checkpoint.Value.gridSearch.reactionIDs, ["R1"; "R3"]);
            testCase.verifyEqual( ...
                checkpoint.Value.gridSearch.fixedFlux, [1, 2; 4, 5]);
            testCase.verifyEqual( ...
                checkpoint.Value.gridSearch.minimumRSS, [6, 4; 8, 6]);
            testCase.verifyEqual( ...
                checkpoint.Value.gridSearch.bestObjective, 3.5);
            testCase.verifyEqual( ...
                checkpoint.Value.gridSearch.maximumTrial, 15);
            testCase.verifyEqual( ...
                checkpoint.Value.gridSearch.workerCount, 8);
            testCase.verifyEqual( ...
                checkpoint.Value.gridSearch.minimumFluxRange, 1e-6);
            testCase.verifyEqual( ...
                checkpoint.Value.gridSearch.elapsedTime, 12.5);
            testCase.verifyEqual(checkpoint.Value.time, 40.25);

        end

