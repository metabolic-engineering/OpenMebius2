        function context = analysisContext(options)

            arguments
                options.ExperimentCount (1, 1) double ...
                    {mustBeInteger, mustBePositive} = 1
            end

            experimentCount = options.ExperimentCount;

            problem = openmebius.mfa.MFAProblem( ...
                Stoichiometry = eye(2), ...
                RightHandSide = [5; 0], ...
                LowerBounds = zeros(2, 1), ...
                UpperBounds = 10 * ones(2, 1), ...
                IndependentMask = [false; true], ...
                BoundaryReactionMask = [false; true]);
            initial = openmebius.mfa.InitialFluxWorkflowResult( ...
                Problem = problem, ...
                Fluxes = [5; 0.8], ...
                RightHandSides = [7; 0.1], ...
                ObjectiveValues = 1);
            iteration = openmebius.mfa.MFAIterationResult( ...
                IndependentValues = 0.8, ...
                Flux = [5; 0.8], ...
                MDV = repmat([0.2; 0.8], 1, experimentCount), ...
                ObjectiveValue = 1, ...
                ExitFlag = 1);
            fitted = openmebius.mfa.MFAWorkflowResult( ...
                ObjectiveValues = 1, ...
                Fluxes = [5; 0.8], ...
                MDVs = reshape( ...
                repmat([0.2; 0.8], 1, experimentCount), ...
                2, experimentCount, 1), ...
                Order = 1, ...
                IterationResults = {iteration});
            data = openmebius.mfa.MFAExperimentalData( ...
                ExperimentalMDV = repmat( ...
                [0.2; 0.8], 1, experimentCount), ...
                FragmentLabels = ["fragment"; "fragment"], ...
                FragmentMask = [true; true]);
            context = openmebius.application.analysis ...
                .MFAAnalysisRunContext();
            context.setExperimentalData(data);
            context.setSubstrateEMUs(repmat({1}, experimentCount, 1));
            context.setInitialResult(initial);
            context.setWorkflowResult(fitted);

        end

        function path = sourcePath()

            path = fullfile( ...
                fileparts(fileparts(mfilename('fullpath'))), ...
            'src');

        end

    end

