                .MFAConfidenceIntervalWorkflow( ...
                ConfidenceIntervalWorkflow = lowLevelWorkflow);
            session = helpers.MFAResultSessionStub();

            result = workflow.run( ...
                helpers.FluxDistributionModelStub(), ...
                MFAConfidenceIntervalApplicationWorkflowTest.settings(), ...
                openmebius.application.analysis ...
                .MFAAnalysisRunContext(), ...
                session, ...
                []);

            testCase.verifyTrue(result.IsCalculated);
            testCase.verifyFalse(result.IsError);
            testCase.verifyEqual(session.Calls, "monte-carlo");
            testCase.verifyEqual(lowLevelWorkflow.CallCount, 1);

        end

