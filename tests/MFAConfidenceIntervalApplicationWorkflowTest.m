                iterationService.LastLinearEqualityRightHandSide, ...
                solver.LastEqualityRightHandSide);
            testCase.verifyEqual( ...
                iterationService.LastInitialIndependentValues, 0.8);
            testCase.verifyEqual( ...
                solver.LastEvaluationResult, iterationResult);
            testCase.verifyFalse(any( ...
                observer.Messages == ...
            "MFA iteration service invoked."));
            testCase.verifyEqual(session.Calls, "grid-search");

        end

