classdef Hdf5ResultRepositoryTest < matlab.unittest.TestCase

    methods (TestMethodSetup)

        function addSourceToPath(~)

            addpath(Hdf5ResultRepositoryTest.sourcePath());

        end

    end

    methods (Test)

        function writeDatasetCreatesHdf5Dataset(testCase)

            resultDirectory = string(tempname);
            mkdir(resultDirectory);
            cleanup = onCleanup(@() ...
                Hdf5ResultRepositoryTest.removeDirectory(resultDirectory));

            repository = openmebius.infrastructure.result.Hdf5ResultRepository();
            pathFile = fullfile(resultDirectory, "result.h5");
            values = [1.0; 2.0; 3.0];

            [isSuccess, msg] = repository.writeDataset( ...
                pathFile, ...
                "/flux", ...
                values);

            testCase.verifyTrue(isSuccess, msg);
            testCase.verifyEqual(h5read(pathFile, "/flux"), values);

            clear cleanup

        end

        function readResultDataReadsHeaderWithoutOptionalSections(testCase)

            resultDirectory = string(tempname);
            mkdir(resultDirectory);
            cleanup = onCleanup(@() ...
                Hdf5ResultRepositoryTest.removeDirectory(resultDirectory));

            repository = openmebius.infrastructure.result ...
                .Hdf5ResultRepository();
            resultLocation = openmebius.domain.result.ResultLocation ...
                .fromDirectory(resultDirectory);
            resultId = "batch-read";
            pathFile = resultLocation.resultFile(resultId);

            [isSuccess, msg] = repository.writeDataset( ...
                pathFile, ...
                "/ID", ...
                resultId, ...
                DataType = "string");
            testCase.assertTrue(isSuccess, msg);

            [isSuccess, msg] = repository.writeDataset( ...
                pathFile, ...
                "/status", ...
                int8([0; 0; 0; 0]), ...
                DataType = "int8");
            testCase.assertTrue(isSuccess, msg);

            data = repository.readResultData( ...
                resultLocation, ...
                resultId, ...
                ReadStatus = false(1, 4));

            testCase.verifyEqual(string(data.ID), resultId);
            testCase.verifyEqual( ...
                logical(data.status(:).'), ...
                false(1, 4));

            clear cleanup

        end

