        end

        function readsOptimizationStateWithoutFluxResults(testCase)

            resultDirectory = string(tempname);
            mkdir(resultDirectory);
            cleanup = onCleanup(@() ...
                Hdf5ResultRepositoryTest.removeDirectory(resultDirectory));
            repository = openmebius.infrastructure.result ...
                .Hdf5ResultRepository();
            resultLocation = openmebius.domain.result.ResultLocation ...
                .fromDirectory(resultDirectory);
            resultId = "batch-optimization";
            pathFile = resultLocation.resultFile(resultId);
            paths = ["/status", "/RSS", "/threshold"];
            values = {int8([0; 1; 0; 0]), [1; 2; 3], 2.5};
            types = ["int8", "double", "double"];

            for index = 1:numel(paths)
                [isSuccess, message] = repository.writeDataset( ...
                    pathFile, paths(index), values{index}, ...
                    DataType = types(index));
                testCase.assertTrue(isSuccess, message);
            end

            data = repository.readOptimizationState( ...
                resultLocation, resultId);

            testCase.verifyEqual(data.RSS, [1; 2; 3]);
            testCase.verifyEqual(data.threshold, 2.5);

            clear cleanup

        end

        function roundTripsGridSearchConfidenceInterval(testCase)

            resultDirectory = string(tempname);
            mkdir(resultDirectory);
            cleanup = onCleanup(@() ...
                Hdf5ResultRepositoryTest.removeDirectory(resultDirectory));
            repository = openmebius.infrastructure.result ...
                .Hdf5ResultRepository();
            resultLocation = openmebius.domain.result.ResultLocation ...
                .fromDirectory(resultDirectory);
            resultId = "batch-grid-search";
            pathFile = resultLocation.resultFile(resultId);
            basePaths = [ ...
                "/ID"; ...
                "/model/modelID"; ...
                "/model/modelReaction"; ...
                "/fluxVariability/fluxUBFwd"; ...
                "/fluxVariability/fluxLBFwd"; ...
                "/RSSIndex"; ...
                "/fluxResult/0001/fluxFwd"];
            baseValues = { ...
                resultId; ...
                "R1"; ...
                "First reaction"; ...
                [2; 3]; ...
                [0; 1]; ...
                int32(1); ...
                [1; 2]};
            baseTypes = [ ...
                "string"; "string"; "string"; ...
                "double"; "double"; "int32"; "double"];

            for index = 1:numel(basePaths)
                [isSuccess, message] = repository.writeDataset( ...
                    pathFile, ...
                    basePaths(index), ...
                    baseValues{index}, ...
                    DataType = baseTypes(index));
                testCase.assertTrue(isSuccess, message);
            end

            profile = openmebius.mfa.GridSearchProfileData( ...
                FluxIndices = 1, ...
                FixedFluxValues = cat(3, [0.5, 1], [0.5, 1]), ...
                MinimumSumOfSquares = cat(3, [6, 4], [5, 3]));
            output = struct( ...
                profile = profile, ...
                time = 2.5, ...
                bestObjective = 2, ...
                objectiveThreshold = 5.5);
            settings = openmebius.mfa.ConfidenceIntervalSettings( ...
                Enabled = true, ...
                Method = openmebius.mfa ...
                .ConfidenceIntervalMethod.GridSearch);
            writer = openmebius.infrastructure.result ...
                .MFAResultCheckpointWriter(Repository = repository);
            checkpoint = writer ...
                .createGridSearchConfidenceIntervalCheckpoint( ...
                0.6, 1.4, settings, output, ["R1"; "biomass"]);

            [isSuccess, message] = ...
                writer.writeGridSearchConfidenceInterval( ...
                pathFile, checkpoint, [1, 1, 1, 0]);
            testCase.assertTrue(isSuccess, message);

            data = repository.readConfidenceInterval( ...
                resultLocation, resultId, "R1");

            testCase.verifyEqual(data.CI.algorithm, "Grid search");
            testCase.verifyEqual( ...
                data.CI.gridSearch.fluxIndices, 1);
            testCase.verifyEqual( ...
                data.CI.gridSearch.reactionIDs, "R1");
            testCase.verifyEqual( ...
                data.CI.gridSearch.fixedFlux, [0.5, 1]);
            testCase.verifyEqual( ...
                data.CI.gridSearch.RSS, ...
                cat(3, [6, 4], [5, 3]));
            testCase.verifyEqual( ...
                data.CI.gridSearch.minimumRSS, [5, 3]);
            testCase.verifyEqual( ...
                data.CI.gridSearch.bestObjective, 2);
            testCase.verifyEqual( ...
                data.CI.gridSearch.objectiveThreshold, 5.5);
            testCase.verifyEqual( ...
                data.CI.gridSearch.maximumTrial, 15);
            testCase.verifyEqual( ...
                data.CI.gridSearch.workerCount, 8);
            testCase.verifyEqual( ...
                data.CI.gridSearch.minimumFluxRange, 1e-6);
            testCase.verifyEqual(data.fluxLB, [0.6; NaN]);
            testCase.verifyEqual(data.fluxUB, [1.4; NaN]);

            resultData = repository.readResultData( ...
                resultLocation, ...
                resultId, ...
                ReadStatus = [false, false, true, false]);
            testCase.verifyEqual( ...
                resultData.CI.algorithm, "Grid search");
            testCase.verifyEqual( ...
                resultData.CI.gridSearch.minimumRSS, [5, 3]);

            clear cleanup

        end

