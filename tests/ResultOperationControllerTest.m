                "Select a result.");
            controller = openmebius.application.result ...
                .ResultOperationController( ...
                ResultExportService = ...
                helpers.ResultExportServiceStub(), ...
                ReportGenerationService = ...
                helpers.ReportGenerationServiceStub(), ...
                ResultRangePlotService = rangeService);

            outcome = controller.prepareRangePlot( ...
                "result", strings(0, 1), strings(0, 1));

            testCase.verifyTrue(outcome.isFailure());
            testCase.verifyEqual( ...
                string(outcome.Exception.identifier), ...
                "OpenMebius2:ResultRangePlot:SelectionRequired");

        end

        function comparesResultSettings(testCase)

            diffService = helpers.ResultDiffServiceStub();
            diffService.Result = openmebius.application.result.ResultDiff( ...
                BatchIDs = ["batch-1"; "batch-2"], ...
                BatchNames = ["First"; "Second"], ...
                Differences = "iteration: 12 -> 30");
            controller = openmebius.application.result ...
                .ResultOperationController( ...
                ResultExportService = ...
                helpers.ResultExportServiceStub(), ...
                ReportGenerationService = ...
                helpers.ReportGenerationServiceStub(), ...
                ResultDiffService = diffService);

            outcome = controller.compareSettings( ...
                "result", ...
                ["batch-1"; "batch-2"], ...
                ["First"; "Second"]);

            testCase.verifyTrue(outcome.isSuccess());
            testCase.verifyTrue(diffService.Called);
            testCase.verifyEqual(diffService.ResultData, "result");
            testCase.verifyEqual( ...
                diffService.BatchIDs, ["batch-1"; "batch-2"]);
            testCase.verifyEqual(outcome.Result, diffService.Result);

        end

    end % methods (Test)

end % classdef
