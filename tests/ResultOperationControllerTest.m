                helpers.ReportGenerationServiceStub(), ...
                ResultSuggestionService = suggestionService);

            outcome = controller.loadSuggestion( ...
                "result", "batch-1", "First");

            testCase.verifyTrue(outcome.isFailure());
            testCase.verifyEqual( ...
                outcome.ErrorMessage, "No suggestion is available.");

        end

        function preparesResultRangePlot(testCase)

            rangeService = helpers.ResultRangePlotServiceStub();
            rangeService.Result = "prepared-range";
            controller = openmebius.application.result ...
                .ResultOperationController( ...
                ResultExportService = ...
                helpers.ResultExportServiceStub(), ...
                ReportGenerationService = ...
                helpers.ReportGenerationServiceStub(), ...
                ResultRangePlotService = rangeService);

            outcome = controller.prepareRangePlot( ...
                "result", ["batch-1"; "batch-2"], ...
                ["First"; "Second"]);

            testCase.verifyTrue(outcome.isSuccess());
            testCase.verifyTrue(rangeService.Called);
            testCase.verifyEqual( ...
                rangeService.BatchIDs, ["batch-1"; "batch-2"]);
            testCase.verifyEqual(outcome.Result, "prepared-range");

        end

        function capturesRangePlotFailure(testCase)

            rangeService = helpers.ResultRangePlotServiceStub();
            rangeService.Exception = MException( ...
