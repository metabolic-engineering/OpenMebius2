                .MFAResultSession(Coordinator = coordinator);
            session.writeGeneral( ...
                "run-1", [], strings(0, 1), false(0, 1));
            session.writeFluxVariability( ...
                [0; 1], [2; 3], zeros(0, 2));
            iteration = openmebius.mfa.MFAIterationResult( ...
                IndependentValues = [5; 2], ...
                Flux = [5; 2], ...
                MDV = [0.3; 0.7], ...
                ObjectiveValue = 4, ...
                ExitFlag = 1);
