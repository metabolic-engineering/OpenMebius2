        function fluxAnalysisPublishesTypedResultEvent(testCase)

            resultDirectory = string(tempname);
            mkdir(resultDirectory);
            cleanup = onCleanup( ...
                @() rmdir(resultDirectory, 's'));
            coordinator = openmebius.infrastructure.result ...
                .MFAResultCoordinator(IsExport = false);
