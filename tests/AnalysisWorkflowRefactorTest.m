                SubstrateEMUFactory = ...
                helpers.SubstrateEMUFactoryStub(), ...
                MDVPredictor = helpers.MDVPredictorStub());
            config = struct;
            config.suggestionTable = {'A'; []};
            config.suggestionTableVarNames = {'Tracer'};
            config.suggestionTableRowNames = {'valid', 'empty'};

            result = workflow.run( ...
                [], [], [1, 2], config, [5; 0.8], ...
                ConfidenceIntervalFunction = ...
                @(mdv, emus) observer.calculate(mdv, emus), ...
