                openmebius.application.analysis ...
                .MFAAnalysisRunContext();
            dependencies.MFAResultCoordinator = coordinator;
            dependencies.MFAExperimentListNormalizer = ...
                openmebius.mfa.MFAExperimentListNormalizer();
            dependencies.FluxDistributionWorkflow = workflow;
            dependencies.AnalysisRunLifecycle = [];
            location = openmebius.domain.result.ResultLocation ...
                .fromDirectory(resultDirectory);
            runtime = openmebius.application.analysis ...
                .FluxAnalysisRuntime( ...
                ResultLocation = location, ...
                ResultID = "run-1", ...
                ResultFilePath = location.resultFile("run-1"), ...
                IsExport = false, ...
                IsError = false, ...
